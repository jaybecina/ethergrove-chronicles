// Godot audio files for the studio (soundtrack spec REQ-19, NFR-01): where the Ogg files live, how ffmpeg makes them,
// how `apps/game/game/audio/audio_manifest.gd` is written from them, and the checks the files must pass.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/** Godot track and total budgets in bytes. */
export const BUDGET = { trackBytes: 1_600_000, totalBytes: 20_000_000 };
/** The web tracks Godot also plays (Sol's cart has no counterpart there). */
export const WEB_TRACKS_FOR_GODOT = [
  'title',
  'spring',
  'summer',
  'fall',
  'winter',
  'night',
  'home',
  'rain',
];
/** Folder, under `apps/game/assets/audio/`, and manifest constant of each kind. */
export const KINDS = { music: 'MUSIC', jingles: 'JINGLES', sfx: 'SFX' };

const ID = /^[A-Za-z0-9-]+$/;

/** The ffmpeg arguments that write `wav` to stdout, a loop trimmed to its seam (start and length in s) when given. */
export function trimArgs(wav, loop) {
  const trim = loop ? ['-ss', String(loop.start), '-t', String(loop.length)] : [];
  return ['-v', 'error', '-i', wav, ...trim, '-f', 'wav', '-'];
}

/** The oggenc arguments: wav on stdin, Ogg Vorbis at quality 3 out (Homebrew's ffmpeg has no libvorbis). */
export function oggencArgs(ogg) {
  return ['-Q', '-q', '3', '-o', ogg, '-'];
}

/** The ids of the `.ogg` files in each kind's folder, sorted. */
export function scanAudio(audioDir) {
  const out = {};
  for (const kind of Object.keys(KINDS)) {
    const dir = join(audioDir, kind);
    out[kind] = existsSync(dir)
      ? readdirSync(dir)
          .filter((f) => f.endsWith('.ogg'))
          .map((f) => f.slice(0, -'.ogg'.length))
          .sort()
      : [];
  }
  return out;
}

/** The text of audio_manifest.gd for the ids found on disk. */
export function manifestSource(ids) {
  const block = (kind) => {
    const entries = ids[kind].map((id) => {
      if (!ID.test(id)) throw new Error(`Bad audio id "${id}"`);
      return `\t"${id}": "res://assets/audio/${kind}/${id}.ogg",`;
    });
    return entries.length === 0 ? '{}' : `{\n${entries.join('\n')}\n}`;
  };
  return `class_name AudioManifest
extends RefCounted
## Generated by scripts/studio.mjs: do not edit. Maps each cue, jingle and sound to its Ogg file. A file that is not
## there yet is skipped by the players, so this stays empty until the studio has rendered the Godot audio.

const MUSIC := ${block('music')}
const JINGLES := ${block('jingles')}
const SFX := ${block('sfx')}
`;
}

/** Problems with the audio folder and manifest (an empty list when fine). */
export function checkAudio(audioDir, manifestPath) {
  const problems = [];
  const ids = scanAudio(audioDir);
  const manifest = existsSync(manifestPath) ? readFileSync(manifestPath, 'utf8') : '';
  let total = 0;
  for (const [kind, constant] of Object.entries(KINDS)) {
    const listed = [
      ...manifest.matchAll(new RegExp(`res://assets/audio/${kind}/([A-Za-z0-9-]+)\\.ogg`, 'g')),
    ].map((m) => m[1]);
    for (const id of listed)
      if (!ids[kind].includes(id))
        problems.push(`${constant} lists ${id} but ${kind}/${id}.ogg is missing`);
    for (const id of ids[kind]) {
      if (!listed.includes(id)) problems.push(`${kind}/${id}.ogg is not in the manifest`);
      const bytes = statSync(join(audioDir, kind, `${id}.ogg`)).size;
      total += bytes;
      if (kind === 'music' && bytes > BUDGET.trackBytes)
        problems.push(
          `${id} is ${String(bytes)} bytes, over the ${String(BUDGET.trackBytes)} track budget`,
        );
    }
  }
  if (total > BUDGET.totalBytes)
    problems.push(`audio totals ${String(total)} bytes, over ${String(BUDGET.totalBytes)}`);
  return problems;
}
